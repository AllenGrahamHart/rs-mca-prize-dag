"""r35 D1 -- ROUTES (a), (b), (c) at m = 4, in ONE currency.

(b) sigma(x) = c/x .  R1.1/R2.1 are verified first, THEN searched.
(c) un-symmetrised: three independent degree-3 pencils, no sharing.
(a) NON-SPLIT G.  The sub-route named here is new and is NOT inside
    (SPLIT-4):

      (QUAD-4)   G(Z,x) = Q(Z,u) * L(Z,u) ,  u = x^2
                 Q = A(u)Z^2 + B(u)Z + C(u) ,  deg_u A,B,C <= 3
                 L = S(u)Z - R(u)           ,  deg_u R,S <= 1

    Q is IRREDUCIBLE over F_q(u) for generic (A,B,C) -- so G does not
    factor into linear-in-Z factors over F_q(x) and this is genuinely
    route (a) -- yet Q is sigma-INVARIANT, so its two roots are shared by
    the orbit {x,-x} exactly as (SPLIT-4)'s swapped pair is.  Its roots
    are in F_q at an orbit iff disc = B^2-4AC is a square there.

    PARAMETER COUNT:  (SPLIT-4) = 7 (A,B deg 3, projective) + 3 (Mobius in
    u) = 10.  (QUAD-4) = 11 (A,B,C deg_u 3, projective) + 3 = 14.
    (SPLIT-4) is the sub-family where disc is a square IN F_q(u).
    So route (a) buys FOUR parameters and pays ~24 square-conditions.

    Also derived here: at EVEN m every sigma-symmetric ansatz wastes one
    unit of the 3m-3 x-degree budget, because a sigma-invariant factor has
    EVEN x-degree (3+3+2 = 8 < 9 split; 6+2 = 8 < 9 quadratic).

Stdlib only.  Checkpointed.
"""

