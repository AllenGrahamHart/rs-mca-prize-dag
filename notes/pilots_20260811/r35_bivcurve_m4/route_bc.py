def mu_N(q, n):
    for c in range(2, q):
        g = pow(c, (q - 1) // n, q)
        seen, x = set(), 1
        for _ in range(n):
            seen.add(x)
            x = x * g % q
        if len(seen) == n:
            return sorted(seen)
    raise RuntimeError


def cev(c, x, q):
    v = 0
    for co in reversed(c):
        v = (v * x + co) % q
    return v


def sqrt_mod(a, q):
    if a == 0:
        return 0
    if pow(a, (q - 1) // 2, q) != 1:
        return None
    if q % 4 == 3:
        return pow(a, (q + 1) // 4, q)
    for r in range(1, q):          # q = 193, 257 are small; direct search ok
        if r * r % q == a:
            return r
    return None


def best_sel(tuples, nedge, degcap, nslope, paircap, budget):
    n = len(tuples)
    deg, pair, chosen = {}, {}, []
    best = [0, []]
    cnt = [0]

    def rec(i):
        if cnt[0] > budget:
            return
        cnt[0] += 1
        if len(chosen) > best[0]:
            best[0] = len(chosen)
            best[1] = list(chosen)
        if len(chosen) == nedge:
            return
        if len(chosen) + (n - i) <= best[0]:
            return
        for j in range(i, n):
            t = tuples[j]
            if any(deg.get(z, 0) >= degcap for z in t):
                continue
            ks = [(min(t[p], t[r]), max(t[p], t[r]))
                  for p in range(len(t)) for r in range(p + 1, len(t))]
            if any(pair.get(k2, 0) >= paircap for k2 in ks):
                continue
            newv = len({z for z in t if z not in deg})
            if len(deg) + newv > nslope:
                continue
            for z in t:
                deg[z] = deg.get(z, 0) + 1
            for k2 in ks:
                pair[k2] = pair.get(k2, 0) + 1
            chosen.append(j)
            rec(j + 1)
            chosen.pop()
            for k2 in ks:
                pair[k2] -= 1
                if pair[k2] == 0:
                    del pair[k2]
            for z in t:
                deg[z] -= 1
                if deg[z] == 0:
                    del deg[z]
            if cnt[0] > budget:
                return

    rec(0)
    return best[0], best[1]


